A = [2, 3, 5, -2, 1;
     4, 1, -1, 3, 6;
     1, 5, 2, 4, -2;
     3, -2, 4, 6, 1;
     5, 1, 3, 2, 7];

b = [7; 24; 19; 19; 23];

n = rows(A);
M = [A, b];

%% ===== Метод Жордана-Гаусса =====

for col = 1:n
  % выбор ведущего элемента: максимум по модулю
  % максим = значение макс, идкс = индекс
  [maxim, idx] = max(abs(M(col:n, col)));
  % реальный номер строки
  p = idx + col - 1;

  % всё ещё мудрый аналог сравнения с нулем
  if maxim < 1e-12
    error("Матрица вырождена, решения нет");
  endif

  % ставим строку с ведущим элементом на место
  if p != col
    % смена строк местами
    M([col, p], :) = M([p, col], :);
  endif

  % делим на ведущий элемент
  M(col, :) = M(col, :) / M(col, col);

  % обнуляем столбец во всех остальных строках
  for r = [1:col-1, col+1:n]
    M(r, :) -= M(r, col) * M(col, :);
  endfor
endfor

M
x = M(:, n+1);

disp("Решение методом Жордана-Гаусса:")
x

disp("Решение встроенным оператором:")
x_ref = A \ b

disp("Невязка:")
err = norm(A*x - b, inf)
